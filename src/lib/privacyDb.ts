import type { PoolClient } from 'pg';

// The privacy tables and columns, run by ensureUserSchema (src/lib/users.ts) inside its transaction on the first
// database use after a deploy, like every other table (the project has no separate migration tool). Every statement
// is additive and safe to run again; nothing existing is dropped or rewritten except as noted. Rolling back the code
// leaves these unused. See docs/privacy.md ("Database changes").
export async function applyPrivacySchema(client: PoolClient): Promise<void> {
  // When the account last signed in, for a future inactive-account rule (none is enforced yet) and for the
  // data export. Null for accounts that haven't signed in since this column was added.
  await client.query('ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ');
  // When the user confirmed they're at least MINIMUM_AGE (src/lib/policyVersions.ts): at signup, or in the updated
  // Terms notice for accounts from before the age requirement
  await client.query('ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS age_confirmed_at TIMESTAMPTZ');

  // Which versions of the Terms of Service (and, as evidence of what was shown, the Privacy Policy) each user
  // accepted, and how: 'signup' or 'website' (src/components/PolicyUpdateNotice.tsx). Deleted with the account.
  await client.query(`CREATE TABLE IF NOT EXISTS "PolicyAcceptances" (
    user_id INTEGER NOT NULL REFERENCES "Users"(id) ON DELETE CASCADE,
    policy TEXT NOT NULL,
    version TEXT NOT NULL,
    source TEXT NOT NULL CHECK (source IN ('signup', 'website')),
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, policy, version)
  )`);

  // The cookie consent audit trail (src/lib/cookieConsentRecords.ts): one row per choice, never updated except to
  // tie a browser's earlier rows to the account that later signs in on it. No IP address or user agent. Kept as
  // evidence after the account is deleted (SET NULL) and purged by the retention job.
  await client.query(`CREATE TABLE IF NOT EXISTS "CookieConsents" (
    id UUID PRIMARY KEY,
    browser_id UUID NOT NULL,
    user_id INTEGER REFERENCES "Users"(id) ON DELETE SET NULL,
    user_linked_at TIMESTAMPTZ,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    action TEXT NOT NULL CHECK (action IN ('accepted', 'rejected', 'customized', 'withdrawn', 'updated')),
    categories JSONB NOT NULL,
    cookie_policy_version TEXT NOT NULL,
    banner_version TEXT NOT NULL,
    purposes_version INTEGER NOT NULL,
    notice_language TEXT NOT NULL,
    method TEXT NOT NULL CHECK (method IN ('banner', 'preferenceCenter'))
  )`);
  await client.query('CREATE INDEX IF NOT EXISTS cookie_consents_browser_id_idx ON "CookieConsents" (browser_id)');
  await client.query('CREATE INDEX IF NOT EXISTS cookie_consents_user_id_idx ON "CookieConsents" (user_id)');
  await client.query('CREATE INDEX IF NOT EXISTS cookie_consents_recorded_at_idx ON "CookieConsents" (recorded_at)');

  // One row per deleted account (src/lib/deletionLedger.ts): the account's ID and creation time, and when it was
  // deleted. No other personal data. Deliberately no foreign key: it's the record that the account is gone, used to
  // delete it again from a restored backup (scripts/reapply-deletions.mjs). Purged by the retention job.
  await client.query(`CREATE TABLE IF NOT EXISTS "DeletionLedger" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    account_created_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, account_created_at)
  )`);

  // Every run of the retention job (src/lib/retention.ts): when, what triggered it, how many rows each rule
  // changed, and any step's error message (never data). Shown on the Admin page.
  await client.query(`CREATE TABLE IF NOT EXISTS "RetentionRuns" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    trigger TEXT NOT NULL CHECK (trigger IN ('cron', 'scheduler', 'admin', 'test')),
    status TEXT NOT NULL CHECK (status IN ('running', 'ok', 'partial', 'failed')),
    results JSONB NOT NULL DEFAULT '{}'::jsonb,
    errors JSONB NOT NULL DEFAULT '{}'::jsonb
  )`);
  await client.query('CREATE INDEX IF NOT EXISTS retention_runs_started_at_idx ON "RetentionRuns" (started_at)');

  // Cancellation reasons lose the name, email and notes after their retention period (the reason stays), so
  // those columns may now be null
  await client.query('ALTER TABLE "CancellationReason" ALTER COLUMN user_name DROP NOT NULL');
  await client.query('ALTER TABLE "CancellationReason" ALTER COLUMN email_address DROP NOT NULL');
  await client.query('ALTER TABLE "CancellationReason" ADD COLUMN IF NOT EXISTS anonymized_at TIMESTAMPTZ');

  // DeepSeek models were removed (src/lib/aiModelList.ts); a saved choice of one falls back to the default
  // anyway, and this removes the stale setting
  await client.query(`DELETE FROM "SiteSettings" WHERE key LIKE 'ai_model:%' AND value LIKE 'deepseek-%'`);
}
